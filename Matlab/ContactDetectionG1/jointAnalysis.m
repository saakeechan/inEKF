%% Ground-truth contacts
l_gt = logical(T.lfoot_contact(1:n));

get_regions = @(contact) deal( ...
    find(diff([0; contact(:); 0]) == 1), ...
    find(diff([0; contact(:); 0]) == -1) - 1);

[l_starts, l_ends] = get_regions(l_gt);
% Read left foot position columns and compute velocity norm
pos_cols = {'lfoot_pos_x', 'lfoot_pos_y', 'lfoot_pos_z'};
pos = zeros(n, numel(pos_cols));
for i = 1:numel(pos_cols)
    if ismember(pos_cols{i}, T.Properties.VariableNames)
        pos(:,i) = T.(pos_cols{i})(1:n);
    else
        error('Column "%s" not found in table.', pos_cols{i});
    end
end

% Compute time differences (dt) and finite-difference velocity
dt = diff(time);
if any(dt <= 0)
    warning('Nonpositive or zero time differences detected; using simple diff.');
end
vel = diff(pos) ./ dt;       % (n-1) x 3, MATLAB broadcasts dt across columns

% Compute Euclidean norm of velocity at each timestep (align with time(2:end))
vel_norm = sqrt(sum(vel.^2, 2));
vel_time = time(2:n);

% Plot velocity norm with ground-truth contact shading
figure;
hold on;
grid on;
plot(vel_time, vel_norm, 'k', 'DisplayName', 'Left foot speed');

y_limits = ylim; % get current y-limits after initial plot may be empty if not plotted yet
% Ensure y_limits reflect plotted data
if isempty(y_limits) || any(isnan(y_limits))
    plot(vel_time, vel_norm, 'k'); % ensure data exists for ylim
    y_limits = ylim;
end

% Plot contact regions in red, hidden from legend
for k = 1:length(l_starts)
    % Convert region indices (which refer to time indices in original time vector)
    % to the velocity time vector indexing where vel_time = time(2:n).
    % Region spans from l_starts(k):l_ends(k) in time indices. We need overlap with vel_time indices.
    x1 = time(l_starts(k));
    x2 = time(l_ends(k));
    h = patch( ...
        [x1 x2 x2 x1], ...
        [y_limits(1) y_limits(1) y_limits(2) y_limits(2)], ...
        [1.0 0.6 0.6], ...
        'FaceAlpha', 0.3, ...
        'EdgeColor', 'none');
    h.Annotation.LegendInformation.IconDisplayStyle = 'off';
end

% Re-plot speed so it stays on top
plot(vel_time, vel_norm, 'k', 'DisplayName', 'Left foot speed');

xlabel('Time [s]');
ylabel('Left foot speed [m/s]');
title('Left Foot Speed (norm of diff(pos)/dt)');

legend;
